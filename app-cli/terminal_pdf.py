"""
terminal_pdf.py – PDF export for Bloomberg-style terminal outputs.

Generates a clean A4 report from any terminal command result:
  - Header with ticker/command, timestamp, user
  - Embedded Plotly charts converted to images
  - Data tables from DataFrames
  - Metric cards
  - Summary text

Entry point: generate_terminal_pdf(title, sections) -> bytes
Each section is a dict with 'type' in:
  'heading', 'text', 'metrics', 'dataframe', 'plotly_fig', 'divider'
"""
import io
from datetime import datetime

import numpy as np
import pandas as pd

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import plotly.graph_objects as go
import plotly.io as pio

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import inch
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate, Table, TableStyle, Paragraph,
    Spacer, Image, HRFlowable, PageBreak,
)

from config import (DARK_HDR, ACCENT, LIGHT_BLUE, ROW_ALT,
                    BORDER_CLR, TEXT_DARK, TEXT_MID)

# ── Colour shortcuts ───────────────────────────────────────────────────────────
WHITE      = colors.white
POS_CLR    = colors.HexColor('#16a34a')
NEG_CLR    = colors.HexColor('#dc2626')
AMBER_CLR  = colors.HexColor('#b45309')
PAGE_W, PAGE_H = A4
BODY_W     = PAGE_W - 1.4 * inch   # usable width


# ── Styles ─────────────────────────────────────────────────────────────────────

def _styles():
    S = getSampleStyleSheet()
    mk = lambda n, p, **kw: ParagraphStyle(n, parent=S[p], **kw)
    return {
        'banner':   mk('BN', 'Normal',  fontSize=8,  textColor=WHITE,
                        fontName='Helvetica', alignment=TA_LEFT),
        'h1':       mk('H1', 'Heading1',fontSize=18, spaceBefore=4, spaceAfter=6,
                        textColor=DARK_HDR, fontName='Helvetica-Bold'),
        'h2':       mk('H2', 'Heading2',fontSize=12, spaceBefore=14, spaceAfter=4,
                        keepWithNext=1, textColor=DARK_HDR, fontName='Helvetica-Bold'),
        'body':     mk('BD', 'Normal',  fontSize=9,  spaceAfter=4,
                        textColor=TEXT_DARK),
        'caption':  mk('CP', 'Normal',  fontSize=7.5,spaceAfter=2, alignment=TA_CENTER,
                        textColor=TEXT_MID, fontName='Helvetica-Oblique'),
        'kv':       mk('KV', 'Normal',  fontSize=13, spaceAfter=1, alignment=TA_CENTER,
                        textColor=ACCENT, fontName='Helvetica-Bold'),
        'kl':       mk('KL', 'Normal',  fontSize=7.5,spaceAfter=0, alignment=TA_CENTER,
                        textColor=TEXT_MID),
        'tbl_hdr':  mk('TH', 'Normal',  fontSize=8.5,fontName='Helvetica-Bold',
                        textColor=WHITE),
        'tbl_cell': mk('TC', 'Normal',  fontSize=8,  textColor=TEXT_DARK),
        'footer':   mk('FT', 'Normal',  fontSize=7,  textColor=TEXT_MID,
                        alignment=TA_CENTER),
    }


# ── Page template (header + footer on every page) ─────────────────────────────

def _make_page_template(title: str, user_email: str):
    def on_page(canvas, doc):
        canvas.saveState()
        # Top banner
        canvas.setFillColor(DARK_HDR)
        canvas.rect(0, PAGE_H - 0.45 * inch, PAGE_W, 0.45 * inch, fill=1, stroke=0)
        canvas.setFillColor(WHITE)
        canvas.setFont('Helvetica-Bold', 9)
        canvas.drawString(0.4 * inch, PAGE_H - 0.28 * inch, f"STRATEGY TERMINAL  |  {title.upper()}")
        canvas.setFont('Helvetica', 8)
        ts = datetime.utcnow().strftime('%Y-%m-%d  %H:%M UTC')
        canvas.drawRightString(PAGE_W - 0.4 * inch, PAGE_H - 0.28 * inch, ts)
        # Footer
        canvas.setFillColor(colors.HexColor('#e2e8f0'))
        canvas.rect(0, 0, PAGE_W, 0.35 * inch, fill=1, stroke=0)
        canvas.setFillColor(TEXT_MID)
        canvas.setFont('Helvetica', 7)
        canvas.drawString(0.4 * inch, 0.12 * inch,
                          f"Generated by Strategy Analyzer  |  {user_email}")
        canvas.drawRightString(PAGE_W - 0.4 * inch, 0.12 * inch,
                               f"Page {doc.page}")
        canvas.restoreState()
    return on_page


# ── Section builders ───────────────────────────────────────────────────────────

def _divider():
    return HRFlowable(width='100%', thickness=1, color=BORDER_CLR,
                      spaceAfter=6, spaceBefore=4)


def _metric_table(metrics: list[dict], S: dict):
    """
    metrics: [{'label': str, 'value': str, 'delta': str|None}, ...]
    """
    if not metrics:
        return Spacer(1, 0)
    cells = []
    for m in metrics:
        delta_str = m.get('delta', '')
        if delta_str:
            try:
                dv = float(str(delta_str).replace('%', '').replace('+', ''))
                delta_clr = POS_CLR if dv >= 0 else NEG_CLR
                delta_para = Paragraph(
                    f'<font color="#{delta_clr.hexval()[2:]}">{delta_str}</font>',
                    S['kl'])
            except:
                delta_para = Paragraph(str(delta_str), S['kl'])
        else:
            delta_para = Paragraph('', S['kl'])

        cells.append([
            Paragraph(str(m.get('value', '—')), S['kv']),
            Paragraph(str(m.get('label', '')), S['kl']),
            delta_para,
        ])

    n   = min(len(cells), 6)
    cw  = BODY_W / n
    # Chunk into rows of n
    rows = [cells[i:i+n] for i in range(0, len(cells), n)]
    story = []
    for row in rows:
        t = Table([row], colWidths=[cw] * len(row))
        t.setStyle(TableStyle([
            ('BOX',           (0, 0), (-1, -1), 1,   BORDER_CLR),
            ('LINEAFTER',     (0, 0), (-2, -1), 0.5, BORDER_CLR),
            ('BACKGROUND',    (0, 0), (-1, -1), LIGHT_BLUE),
            ('TOPPADDING',    (0, 0), (-1, -1), 8),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
            ('VALIGN',        (0, 0), (-1, -1), 'MIDDLE'),
        ]))
        story.append(t)
        story.append(Spacer(1, 6))
    return story


def _df_table(df: pd.DataFrame, S: dict, max_rows: int = 40):
    """Convert a DataFrame to a ReportLab Table."""
    if df.empty:
        return Paragraph("No data.", S['body'])

    df = df.head(max_rows).copy()
    col_count = len(df.columns) + 1   # +1 for index if not default int
    show_index = not isinstance(df.index, pd.RangeIndex)

    headers = ([str(df.index.name or '#')] if show_index else []) + \
              [str(c) for c in df.columns]
    col_w   = BODY_W / len(headers)

    data = [[Paragraph(h, S['tbl_hdr']) for h in headers]]
    for idx, row in df.iterrows():
        cells = []
        if show_index:
            cells.append(Paragraph(str(idx), S['tbl_cell']))
        for val in row:
            if isinstance(val, float) and np.isnan(val):
                txt = '—'
            else:
                txt = str(val)
            cells.append(Paragraph(txt, S['tbl_cell']))
        data.append(cells)

    t = Table(data, colWidths=[col_w] * len(headers), repeatRows=1)
    t.setStyle(TableStyle([
        ('BACKGROUND',    (0, 0), (-1,  0), DARK_HDR),
        ('TEXTCOLOR',     (0, 0), (-1,  0), WHITE),
        ('FONTNAME',      (0, 0), (-1,  0), 'Helvetica-Bold'),
        ('FONTSIZE',      (0, 0), (-1,  0), 8.5),
        ('TOPPADDING',    (0, 0), (-1,  0), 6),
        ('BOTTOMPADDING', (0, 0), (-1,  0), 6),
        ('FONTNAME',      (0, 1), (-1, -1), 'Helvetica'),
        ('FONTSIZE',      (0, 1), (-1, -1), 8),
        ('ROWBACKGROUNDS',(0, 1), (-1, -1), [WHITE, ROW_ALT]),
        ('TOPPADDING',    (0, 1), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 1), (-1, -1), 4),
        ('LINEBELOW',     (0, 0), (-1,  0), 1.2, DARK_HDR),
        ('LINEBELOW',     (0, 1), (-1, -1), 0.4, BORDER_CLR),
        ('BOX',           (0, 0), (-1, -1), 0.8, BORDER_CLR),
        ('LEFTPADDING',   (0, 0), (-1, -1), 5),
        ('RIGHTPADDING',  (0, 0), (-1, -1), 5),
    ]))
    return t


def _plotly_to_image(fig: go.Figure, width_px: int = 900, height_px: int = 380) -> Image | None:
    """Rasterise a Plotly figure to a ReportLab Image."""
    try:
        # Use kaleido if available (best quality)
        buf = io.BytesIO(pio.to_image(fig, format='png',
                                       width=width_px, height=height_px, scale=2))
        aspect = height_px / width_px
        return Image(buf, width=BODY_W, height=BODY_W * aspect)
    except Exception:
        pass
    try:
        # Fallback: matplotlib rendering via fig.to_dict (very basic)
        import plotly.io as pio2
        buf = io.BytesIO()
        fig.write_image(buf, format='png', width=width_px, height=height_px)
        buf.seek(0)
        aspect = height_px / width_px
        return Image(buf, width=BODY_W, height=BODY_W * aspect)
    except:
        return None


# ── Main export function ───────────────────────────────────────────────────────

def generate_terminal_pdf(
    title: str,
    sections: list[dict],
    user_email: str = '',
    subtitle: str = '',
) -> bytes:
    """
    Build and return a PDF as bytes.

    sections is a list of dicts, each with 'type' key:

      {'type': 'heading',    'text': str, 'level': 1|2}
      {'type': 'text',       'text': str}
      {'type': 'divider'}
      {'type': 'spacer',     'height': float}   # in points
      {'type': 'metrics',    'items': [{'label','value','delta'}, ...]}
      {'type': 'dataframe',  'df': pd.DataFrame, 'caption': str, 'max_rows': int}
      {'type': 'plotly_fig', 'fig': go.Figure,   'caption': str,
                              'width': int, 'height': int}
      {'type': 'pagebreak'}
    """
    buf = io.BytesIO()
    S   = _styles()

    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=0.7 * inch,
        rightMargin=0.7 * inch,
        topMargin=0.65 * inch,
        bottomMargin=0.5 * inch,
        title=title,
        author='Strategy Analyzer Terminal',
    )

    on_page = _make_page_template(title, user_email)
    story   = []

    # ── Cover block ──
    story.append(Spacer(1, 0.15 * inch))
    story.append(Paragraph(title, S['h1']))
    if subtitle:
        story.append(Paragraph(subtitle, S['body']))
    ts_str = datetime.utcnow().strftime('%d %B %Y  %H:%M UTC')
    story.append(Paragraph(
        f'<font color="#475569">Generated: {ts_str}'
        + (f'  |  {user_email}' if user_email else '') + '</font>',
        S['caption']))
    story.append(_divider())
    story.append(Spacer(1, 0.1 * inch))

    # ── Body sections ──
    for sec in sections:
        stype = sec.get('type', '')

        if stype == 'heading':
            level = sec.get('level', 2)
            style = S['h1'] if level == 1 else S['h2']
            story.append(Paragraph(sec.get('text', ''), style))

        elif stype == 'text':
            story.append(Paragraph(sec.get('text', ''), S['body']))

        elif stype == 'divider':
            story.append(_divider())

        elif stype == 'spacer':
            story.append(Spacer(1, sec.get('height', 12)))

        elif stype == 'pagebreak':
            story.append(PageBreak())

        elif stype == 'metrics':
            items = sec.get('items', [])
            metric_story = _metric_table(items, S)
            if isinstance(metric_story, list):
                story.extend(metric_story)
            else:
                story.append(metric_story)

        elif stype == 'dataframe':
            df = sec.get('df')
            if df is not None and not (hasattr(df, 'empty') and df.empty):
                tbl = _df_table(df, S, max_rows=sec.get('max_rows', 40))
                story.append(tbl)
                if sec.get('caption'):
                    story.append(Paragraph(sec['caption'], S['caption']))
                story.append(Spacer(1, 8))

        elif stype == 'plotly_fig':
            fig = sec.get('fig')
            if fig is not None:
                w = sec.get('width',  900)
                h = sec.get('height', 380)
                img = _plotly_to_image(fig, width_px=w, height_px=h)
                if img:
                    story.append(img)
                    if sec.get('caption'):
                        story.append(Paragraph(sec['caption'], S['caption']))
                    story.append(Spacer(1, 8))
                else:
                    story.append(Paragraph(
                        f"[Chart: {sec.get('caption','figure')} — "
                        f"install `kaleido` for chart export: pip install kaleido]",
                        S['caption']))

    # ── Disclaimer footer ──
    story.append(Spacer(1, 0.2 * inch))
    story.append(_divider())
    story.append(Paragraph(
        "This report is generated by Strategy Analyzer Terminal for informational purposes only. "
        "Data sourced from yfinance, FRED, and other public APIs. "
        "Not financial advice. Past performance does not guarantee future results.",
        S['caption']))

    doc.build(story, onFirstPage=on_page, onLaterPages=on_page)
    return buf.getvalue()
